'''
Desenvolva um código python com while 
em que o usuáruo digita um número 
e irá mostrar a tabuada deste número
'''
v=int(input("Digite um valor "))
i=0
while i <= 10:
    r = i * v
    print(f"{v} x {i} = {r}")
    i += 1
    
